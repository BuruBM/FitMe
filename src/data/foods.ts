export function searchLocalFoods(query: string): FoodItem[] {
  const q = query.trim().toLowerCase();
  if (!q) return FOODS.slice(0, 8);
  const terms = q.split(/\s+/).filter(Boolean);
  return FOODS.filter((f) => {
    const haystack = `${f.name} ${f.tags.join(" ")}`.toLowerCase();
    return terms.every((t) => haystack.includes(t));
  }).slice(0, 20);
}

/**
 * Rule-based estimator for free-text meals like "milanesa de soja con ensalada y arroz".
 * Splits on common connectors and matches each chunk against the local DB.
 * No external AI call — deterministic and free. Falls back gracefully when a
 * chunk has no match (caller shows it as "no encontrado" for manual entry).
 */
export function estimateFromText(text: string): { matched: FoodItem[]; unmatched: string[] } {
  const chunks = text
    .toLowerCase()
    .split(/,| y | con | \+ /)
    .map((c) => c.trim())
    .filter(Boolean);

  const matched: FoodItem[] = [];
  const unmatched: string[] = [];

  for (const chunk of chunks) {
    const results = searchLocalFoods(chunk);
    if (results.length > 0) {
      matched.push(results[0]);
    } else {
      unmatched.push(chunk);
    }
  }

  return { matched, unmatched };
}
